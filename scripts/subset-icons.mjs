#!/usr/bin/env node
/**
 * Generates a Material Symbols subset containing only the icon names used in
 * src/. Run `npm run icons:subset` after adding an icon; `npm run icons:check`
 * (CI) fails when a referenced icon is missing from the committed subset.
 */
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import subsetFont from 'subset-font';

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, 'src');
const FONT_PATH = path.join(ROOT, 'node_modules/material-symbols/material-symbols-outlined.woff2');
const OUT_FONT = path.join(SRC_DIR, 'assets/material-symbols-subset.woff2');
const OUT_CSS = path.join(SRC_DIR, 'styles/icons.css');
const MANIFEST = path.join(SRC_DIR, 'assets/material-symbols-subset.manifest.json');

const ICON_NAME = /^[a-z][a-z0-9_]*$/;

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

function extractIcons(sources) {
  const icons = new Set();

  for (const source of sources) {
    for (const match of source.matchAll(/material-symbols-outlined[^>]*>([\s\S]*?)<\/span>/g)) {
      const inner = match[1].replace(/<[^>]+>/g, ' ');

      // Plain-text icons: <span class="material-symbols-outlined">play_arrow</span>
      if (!inner.includes('{')) {
        const name = inner.trim();
        if (ICON_NAME.test(name)) icons.add(name);
      }

      // Icons produced by a ternary/expression inside the span.
      for (const quoted of inner.matchAll(/['"]([a-z][a-z0-9_]*)['"]/g)) icons.add(quoted[1]);
    }

    // <EmptyState icon="search_off" /> and icon={condition ? 'pause' : 'play_arrow'}
    for (const match of source.matchAll(/icon\s*=\s*"([a-z][a-z0-9_]*)"/g)) icons.add(match[1]);
    for (const match of source.matchAll(/icon\s*=\s*\{([^}]*)\}/g)) {
      for (const quoted of match[1].matchAll(/['"]([a-z][a-z0-9_]*)['"]/g)) icons.add(quoted[1]);
    }

    // Static icon maps (e.g. toast kind -> icon).
    for (const match of source.matchAll(/const\s+ICONS[^=]*=\s*\{([\s\S]*?)\};/g)) {
      for (const quoted of match[1].matchAll(/['"]([a-z][a-z0-9_]*)['"]/g)) icons.add(quoted[1]);
    }
  }

  return [...icons].sort();
}

const CSS = `/* Generated by scripts/subset-icons.mjs — do not edit by hand. */@font-face {
  font-family: 'Material Symbols Outlined';
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url('../assets/material-symbols-subset.woff2') format('woff2');
}

.material-symbols-outlined {
  font-family: 'Material Symbols Outlined';
  font-weight: normal;
  font-style: normal;
  font-size: 24px;
  line-height: 1;
  letter-spacing: normal;
  text-transform: none;
  display: inline-block;
  white-space: nowrap;
  word-wrap: normal;
  direction: ltr;
  font-feature-settings: 'liga';
  -webkit-font-feature-settings: 'liga';
  -webkit-font-smoothing: antialiased;
  font-variation-settings:
    'FILL' 0,
    'wght' 400,
    'GRAD' 0,
    'opsz' 24;
}
`;

async function collectIcons() {
  const files = (await walk(SRC_DIR)).filter(
    (file) => /\.(ts|tsx)$/.test(file) && !/\.(test|spec)\./.test(file),
  );
  const sources = await Promise.all(files.map((file) => readFile(file, 'utf8')));
  return extractIcons(sources);
}

const icons = await collectIcons();
if (icons.length === 0) throw new Error('No icon names found in src/.');

if (process.argv.includes('--check')) {
  const manifest = JSON.parse(await readFile(MANIFEST, 'utf8'));
  const known = new Set(manifest.icons);
  const missing = icons.filter((icon) => !known.has(icon));

  if (missing.length > 0) {
    console.error(
      `icons:check failed — missing from the subset: ${missing.join(', ')}.\nRun "npm run icons:subset" and commit the result.`,
    );
    process.exit(1);
  }

  console.log(`icons:check passed (${icons.length} icons in use).`);
  process.exit(0);
}

const CODEPOINTS_URL =
  'https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints';

/** Material Symbols name -> private-use codepoint. */
async function loadCodepoints() {
  const response = await fetch(CODEPOINTS_URL);
  if (!response.ok) {
    throw new Error(
      `Could not download Material Symbols codepoints (HTTP ${response.status}). Regeneration needs network access.`,
    );
  }

  const map = new Map();
  for (const line of (await response.text()).trim().split('\n')) {
    const [name, codepoint] = line.trim().split(/\s+/);
    if (name && codepoint) map.set(name, Number.parseInt(codepoint, 16));
  }
  return map;
}

const codepoints = await loadCodepoints();
const unknown = icons.filter((icon) => !codepoints.has(icon));
if (unknown.length > 0) {
  throw new Error(`Unknown Material Symbols icon names: ${unknown.join(', ')}.`);
}

// Include the ASCII glyphs used by ligature names plus the icon glyphs
// themselves. Layout closure is disabled: enabling it for `rlig` would retain
// every icon reachable from ASCII sequences (hundreds of KB).
const printableAscii = Array.from({ length: 0x7f - 0x20 }, (_, index) =>
  String.fromCodePoint(0x20 + index),
).join('');
const subsetText =
  printableAscii + icons.map((icon) => String.fromCodePoint(codepoints.get(icon))).join('');

const font = await readFile(FONT_PATH);
const subset = await subsetFont(font, subsetText, {
  targetFormat: 'woff2',
  keepFeatures: ['liga', 'rlig'],
  noLayoutClosure: true,
  noHinting: true,
  variationAxes: { wght: 400, FILL: 0, GRAD: 0, opsz: 24 },
});

await mkdir(path.dirname(OUT_FONT), { recursive: true });
await writeFile(OUT_FONT, subset);
await writeFile(OUT_CSS, CSS);
await writeFile(MANIFEST, `${JSON.stringify({ icons }, null, 2)}\n`);

console.log(
  `Wrote ${path.relative(ROOT, OUT_FONT)} (${(subset.length / 1024).toFixed(1)} KB) with ${icons.length} icons.`,
);
console.log(`Wrote ${path.relative(ROOT, OUT_CSS)} and the manifest.`);
